"""Entry points for the generated finite-window GNU Radio skill."""
import numpy as np
from skill_io import run_graph


def process_window(iq, metadata, context):
    return run_graph(iq, metadata, context)[0]


def transmit_waveform(context, samples):
    channels = len(context['channels'])
    iq = np.zeros((context['window_samples'], channels), np.complex64)
    metadata = {'index': 0, 'timestamp_ns': 0, 'sample_start': 0, 'samples': len(iq)}
    _, tx = run_graph(iq, metadata, context, tx_samples=samples, measure=False)
    if len(tx) != samples:
        raise ValueError('No complete TX waveform was generated by the skill graph')
    return tx
